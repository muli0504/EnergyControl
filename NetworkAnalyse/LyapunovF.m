function ly=LyapunovF(f)
m=400000;
h=0.005;
a=0.3;
b=1.0;
c=0.1;
apha=0.1;
beta=0.77;
A=0.828;
k1=1.0;
k2=1.8;
u0=0;
y=zeros(m,3);
I=eye(3);
Q=eye(3);
ly1=0;
ly2=0;
ly3=0;
x0=0.2;
y0=0.1;
z0=0.05;
for i=1:m
    t=(i-1)*h;
    Iext1=u0+A*cos(2*pi*f*t);
    k11=-(apha+beta*z0^2)*(x0-Iext1)-y0+x0-(1/3)*x0^3;
    k21=c*(x0+a-b*y0);
    k31=-k1*(x0-Iext1)-k2*z0;
    Iext2=u0+A*cos(2*pi*f*(t+0.5*h));
    xt2=x0+0.5*h*k11;
    yt2=y0+0.5*h*k21;
    zt2=z0+0.5*h*k31;
    k12=-(apha+beta*zt2^2)*(xt2-Iext2)-yt2+xt2-(1/3)*xt2^3;
    k22=c*(xt2+a-b*yt2);
    k32=-k1*(xt2-Iext2)-k2*zt2;
    Iext3=u0+A*cos(2*pi*f*(t+0.5*h));
    xt3=x0+0.5*h*k12;
    yt3=y0+0.5*h*k22;
    zt3=z0+0.5*h*k32;
    k13=-(apha+beta*zt3^2)*(xt3-Iext3)-yt3+xt3-(1/3)*xt3^3;
    k23=c*(xt3+a-b*yt3);
    k33=-k1*(xt3-Iext3)-k2*zt3;
    Iext4=u0+A*cos(2*pi*f*(t+h));
    xt4=x0+h*k13;
    yt4=y0+h*k23;
    zt4=z0+h*k33;
    k14=-(apha+beta*zt4^2)*(xt4-Iext4)-yt4+xt4-(1/3)*xt4^3;
    k24=c*(xt4+a-b*yt4);
    k34=-k1*(xt4-Iext4)-k2*zt4;
    x0=x0+h*(k11+2*k12+2*k13+k14)/6;
    y0=y0+h*(k21+2*k22+2*k23+k24)/6;
    z0=z0+h*(k31+2*k32+2*k33+k34)/6;
    y(i,1)=x0;
    y(i,2)=y0;
    y(i,3)=z0;
    if(i>100000)
        J1=[1-x0^2-apha-beta*z0^2,   -1,   -2*beta*z0*(x0-Iext1);
            c,                       -b*c,  0;
            -k1,                     0,     -k2];
        xt2j=x0+0.5*h*k11;
        yt2j=y0+0.5*h*k21;
        zt2j=z0+0.5*h*k31;
        J2=[1-xt2j^2-apha-beta*zt2j^2,   -1,   -2*beta*zt2j*(xt2j-Iext2);
            c,                           -b*c,  0;
            -k1,                         0,     -k2];
        xt3j=x0+0.5*h*k12;
        yt3j=y0+0.5*h*k22;
        zt3j=z0+0.5*h*k32;
        J3=[1-xt3j^2-apha-beta*zt3j^2,   -1,   -2*beta*zt3j*(xt3j-Iext3);
            c,                           -b*c,  0;
            -k1,                         0,     -k2];
        xt4j=x0+h*k13;
        yt4j=y0+h*k23;
        zt4j=z0+h*k33;
        J4=[1-xt4j^2-apha-beta*zt4j^2,   -1,   -2*beta*zt4j*(xt4j-Iext4);
            c,                           -b*c,  0;
            -k1,                         0,     -k2];
        J=I+h*(J1+2*J2*(I+0.5*h*J1)+2*J3*(I+0.5*h*J2*(I+0.5*h*J1))+J4*(I+h*J3*(I+0.5*h*J2*(I+0.5*h*J1))))/6;
        B=J*Q;
        [Q,R]=qr(B);
        ly1=ly1+log(abs(R(1,1)));
        ly2=ly2+log(abs(R(2,2)));
        ly3=ly3+log(abs(R(3,3)));
    end
end
ly(1)=ly1/((m-100000)*h);
ly(2)=ly2/((m-100000)*h);
ly(3)=ly3/((m-100000)*h);
end
